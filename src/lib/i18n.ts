export const MESSAGES: Record<Lang, Dict> = { uz, ru, en };

export function isLang(v: unknown): v is Lang {
  return v === "uz" || v === "ru" || v === "en";
}

/** Tarjima: kalit topilmasa o'zbekcha, u ham bo'lmasa kalitning o'zi. {nom} — o'rniga qo'yiladi. */
export function translate(lang: Lang, key: MsgKey, vars?: Record<string, string | number>): string {
  let s = MESSAGES[lang]?.[key] ?? uz[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v));
  return s;
}

const UZ_CYRILLIC_LETTERS = /[ўқғҳЎҚҒҲ]/;
// Kirillda yozilgan o'zbekcha buyruqlarga xos so'zlar (maxsus harflarsiz yozilganda ham)
const UZ_CYRILLIC_WORDS = /(?:^|[\s"«'’])(ни|оч|очиб|очгин|ярат|яратинг|қидир|кидир|ишга|папкани|учун|билан|ва)(?=$|[\s.,!?"»])/i;
const CYRILLIC = /[Ѐ-ӿ]/;

/**
 * Yozilgan buyruq tili. Kirill — avval ruscha deb qabul qilinardi, lekin o'zbek kirill yozuvi ham bor:
 * ў/қ/ғ/ҳ harflari yoki o'zbekcha buyruq so'zlari bo'lsa — "uz". Lotin yozuvi — tanlangan til.
 */
export function detectCommandLanguage(text: string, selected: Lang): Lang {
  if (!CYRILLIC.test(text)) return selected;
  if (UZ_CYRILLIC_LETTERS.test(text)) return "uz";
  if (UZ_CYRILLIC_WORDS.test(text)) return "uz";
  if (selected === "uz" && /[Ѐ-ӿ]ни(?=\s|$)/.test(text)) return "uz";   // "Телеграмни ..."
  return "ru";
}
